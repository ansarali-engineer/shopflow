def get_customers_ranked_by_spending():
    """Rank all customers by spending with quartiles (RANK + NTILE)."""
    sql = """
        SELECT o.customer_id, u.email, u.first_name, u.last_name,
               COALESCE(SUM(o.total_amount), 0) AS total_spent, COUNT(*) AS order_count,
               RANK() OVER (ORDER BY COALESCE(SUM(o.total_amount), 0) DESC) AS spending_rank,
               NTILE(4) OVER (ORDER BY COALESCE(SUM(o.total_amount), 0) DESC) AS quartile
        FROM orders o INNER JOIN users u ON o.customer_id = u.id
        WHERE o.status NOT IN ('CANCELLED','REFUNDED')
        GROUP BY o.customer_id, u.email, u.first_name, u.last_name
        ORDER BY spending_rank
    """
    return fetch_all(sql)


def get_consecutive_declining_months():
    """Identify consecutive periods of declining sales (LAG + conditional)."""
    sql = """
        WITH monthly AS (
            SELECT DATE_FORMAT(o.created_at, '%%Y-%%m') AS month,
                   COALESCE(SUM(o.total_amount), 0) AS revenue
            FROM orders o WHERE o.status NOT IN ('CANCELLED','REFUNDED')
            GROUP BY DATE_FORMAT(o.created_at, '%%Y-%%m')
        ),
        with_lag AS (
            SELECT month, revenue,
                   LAG(revenue) OVER (ORDER BY month) AS prev_revenue,
                   CASE WHEN LAG(revenue) OVER (ORDER BY month) IS NOT NULL
                        AND revenue < LAG(revenue) OVER (ORDER BY month) THEN 1 ELSE 0 END AS is_decline
            FROM monthly
        )
        SELECT month, revenue, prev_revenue, is_decline
        FROM with_lag ORDER BY month
    """
    return fetch_all(sql)


def get_order_status_summary():
    """Summary of orders by status using conditional aggregation."""
    sql = """
        SELECT COUNT(*) AS total_orders,
               SUM(CASE WHEN status = 'PENDING_PAYMENT' THEN 1 ELSE 0 END) AS pending_payment,
               SUM(CASE WHEN status = 'PAID' THEN 1 ELSE 0 END) AS paid,
               SUM(CASE WHEN status = 'PROCESSING' THEN 1 ELSE 0 END) AS processing,
               SUM(CASE WHEN status = 'SHIPPED' THEN 1 ELSE 0 END) AS shipped,
               SUM(CASE WHEN status = 'DELIVERED' THEN 1 ELSE 0 END) AS delivered,
               SUM(CASE WHEN status = 'CANCELLED' THEN 1 ELSE 0 END) AS cancelled,
               SUM(CASE WHEN status = 'REFUNDED' THEN 1 ELSE 0 END) AS refunded,
               COALESCE(SUM(CASE WHEN status NOT IN ('CANCELLED','REFUNDED')
                   THEN total_amount ELSE 0 END), 0) AS active_revenue,
               COALESCE(SUM(CASE WHEN status = 'REFUNDED'
                   THEN total_amount ELSE 0 END), 0) AS refunded_amount
        FROM orders
    """
    return fetch_one(sql)


def get_orders_keyset_paginated(last_id=0, limit=20):
    """Keyset pagination for large order lists."""
    sql = """
        SELECT o.id, o.order_number, o.customer_id, u.email AS customer_email,
               o.status, o.total_amount, o.created_at,
               (SELECT COUNT(*) FROM order_items oi WHERE oi.order_id = o.id) AS item_count
        FROM orders o INNER JOIN users u ON o.customer_id = u.id
        ORDER BY o.id ASC
    """
    rows, next_cursor = fetch_keyset_paginated(sql, [], last_id, limit)
    return rows, next_cursor


def get_inventory_alerts(threshold=10):
    """Dashboard alert for low-stock and out-of-stock items."""
    sql = """
        SELECT pv.id AS variant_id, pv.sku, pv.variant_name, p.name AS product_name,
               c.name AS category_name, pv.stock_quantity, pv.reserved_quantity,
               (pv.stock_quantity - pv.reserved_quantity) AS available_stock,
               CASE WHEN (pv.stock_quantity - pv.reserved_quantity) <= 0 THEN 'OUT_OF_STOCK'
                    WHEN (pv.stock_quantity - pv.reserved_quantity) < %s THEN 'LOW_STOCK'
                    ELSE 'IN_STOCK' END AS stock_status,
               u.email AS seller_email
        FROM product_variants pv
        INNER JOIN products p ON pv.product_id = p.id
        INNER JOIN categories c ON p.category_id = c.id
        INNER JOIN users u ON p.seller_id = u.id
        WHERE pv.status = 'active' AND (pv.stock_quantity - pv.reserved_quantity) < %s
        ORDER BY available_stock ASC
    """
    return fetch_all(sql, [threshold, threshold])
