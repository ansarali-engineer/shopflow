def get_monthly_revenue_report():
    """Monthly revenue with month-over-month change (CTE + LAG)."""
    sql = """
        WITH monthly_revenue AS (
            SELECT DATE_FORMAT(o.created_at, '%%Y-%%m') AS month,
                   COALESCE(SUM(o.total_amount), 0) AS revenue, COUNT(*) AS order_count
            FROM orders o WHERE o.status NOT IN ('CANCELLED','REFUNDED')
            GROUP BY DATE_FORMAT(o.created_at, '%%Y-%%m')
        )
        SELECT month, revenue, order_count,
               LAG(revenue) OVER (ORDER BY month) AS prev_month_revenue,
               revenue - LAG(revenue) OVER (ORDER BY month) AS mom_change,
               CASE WHEN LAG(revenue) OVER (ORDER BY month) IS NULL THEN NULL
                    WHEN LAG(revenue) OVER (ORDER BY month) = 0 THEN NULL
                    ELSE ROUND((revenue - LAG(revenue) OVER (ORDER BY month))
                        / LAG(revenue) OVER (ORDER BY month) * 100, 2)
               END AS mom_change_pct
        FROM monthly_revenue ORDER BY month
    """
    return fetch_all(sql)


def get_customer_lifetime_value():
    """Customer LTV with spending tier segmentation (CTE + CASE WHEN)."""
    sql = """
        WITH customer_spending AS (
            SELECT o.customer_id, u.email, u.first_name, u.last_name,
                   COUNT(*) AS total_orders, COALESCE(SUM(o.total_amount), 0) AS lifetime_value,
                   MIN(o.created_at) AS first_order_date, MAX(o.created_at) AS last_order_date
            FROM orders o INNER JOIN users u ON o.customer_id = u.id
            WHERE o.status NOT IN ('CANCELLED','REFUNDED')
            GROUP BY o.customer_id, u.email, u.first_name, u.last_name
        )
        SELECT customer_id, email, first_name, last_name, total_orders, lifetime_value,
               first_order_date, last_order_date,
               CASE WHEN lifetime_value > 10000 THEN 'VIP'
                    WHEN lifetime_value > 1000 THEN 'High Value'
                    WHEN lifetime_value > 100 THEN 'Regular'
                    ELSE 'New' END AS spending_tier
        FROM customer_spending ORDER BY lifetime_value DESC
    """
    return fetch_all(sql)


def get_product_sales_ranking():
    """Product sales ranking with RANK and DENSE_RANK."""
    sql = """
        SELECT p.id AS product_id, p.name AS product_name, c.name AS category_name,
               COALESCE(SUM(oi.quantity * oi.unit_price), 0) AS revenue,
               SUM(oi.quantity) AS units_sold,
               RANK() OVER (ORDER BY COALESCE(SUM(oi.quantity * oi.unit_price), 0) DESC) AS rank_overall,
               DENSE_RANK() OVER (ORDER BY COALESCE(SUM(oi.quantity * oi.unit_price), 0) DESC) AS dense_rank_overall,
               RANK() OVER (PARTITION BY c.id ORDER BY COALESCE(SUM(oi.quantity * oi.unit_price), 0) DESC) AS rank_in_category
        FROM products p INNER JOIN categories c ON p.category_id = c.id
        LEFT JOIN order_items oi ON oi.product_id = p.id
        LEFT JOIN orders o ON o.id = oi.order_id AND o.status NOT IN ('CANCELLED','REFUNDED')
        GROUP BY p.id, p.name, c.id, c.name ORDER BY rank_overall
    """
    return fetch_all(sql)


def get_category_revenue_rollup():
    """Revenue rollup across category hierarchy (recursive CTE)."""
    sql = """
        WITH RECURSIVE category_tree AS (
            SELECT id, name, slug, parent_id, 0 AS depth,
                   CAST(id AS CHAR(255)) AS sort_path, CAST(id AS CHAR(255)) AS ancestor_id
            FROM categories
            UNION ALL
            SELECT c.id, c.name, c.slug, c.parent_id, ct.depth + 1,
                   CONCAT(ct.sort_path, '-', c.id), ct.ancestor_id
            FROM categories c INNER JOIN category_tree ct ON c.parent_id = ct.id
        ),
        category_sales AS (
            SELECT p.category_id, COALESCE(SUM(oi.quantity * oi.unit_price), 0) AS direct_revenue
            FROM products p
            LEFT JOIN order_items oi ON oi.product_id = p.id
            LEFT JOIN orders o ON o.id = oi.order_id AND o.status NOT IN ('CANCELLED','REFUNDED')
            GROUP BY p.category_id
        )
        SELECT ct.ancestor_id AS category_id, c.name AS category_name, c.slug, c.parent_id, ct.depth,
               COALESCE(SUM(cs.direct_revenue), 0) AS total_revenue_including_descendants,
               COALESCE((SELECT direct_revenue FROM category_sales cs2 WHERE cs2.category_id = ct.ancestor_id), 0) AS direct_revenue
        FROM category_tree ct INNER JOIN categories c ON ct.ancestor_id = c.id
        LEFT JOIN category_sales cs ON ct.id = cs.category_id
        GROUP BY ct.ancestor_id, c.name, c.slug, c.parent_id, ct.depth
        ORDER BY ct.depth, total_revenue_including_descendants DESC
    """
    return fetch_all(sql)


def get_sales_window_analysis():
    """Comprehensive sales analysis with multiple window functions."""
    sql = """
        WITH monthly AS (
            SELECT DATE_FORMAT(o.created_at, '%%Y-%%m') AS month,
                   COALESCE(SUM(o.total_amount), 0) AS revenue, COUNT(*) AS order_count
            FROM orders o WHERE o.status NOT IN ('CANCELLED','REFUNDED')
            GROUP BY DATE_FORMAT(o.created_at, '%%Y-%%m')
        )
        SELECT month, revenue, order_count,
               LAG(revenue) OVER (ORDER BY month) AS prev_month,
               LEAD(revenue) OVER (ORDER BY month) AS next_month,
               SUM(revenue) OVER (ORDER BY month ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW) AS running_total,
               AVG(revenue) OVER (ORDER BY month ROWS BETWEEN 2 PRECEDING AND CURRENT ROW) AS moving_avg_3mo,
               ROUND(revenue / NULLIF(SUM(revenue) OVER (), 0) * 100, 2) AS pct_of_total
        FROM monthly ORDER BY month
    """
    return fetch_all(sql)


