def get_categories_above_average_revenue():
    """Categories with revenue above the overall category average."""
    sql = """
        SELECT c.id AS category_id, c.name AS category_name,
               COALESCE(SUM(oi.quantity * oi.unit_price), 0) AS category_revenue
        FROM order_items oi
        INNER JOIN orders o ON oi.order_id = o.id
        INNER JOIN products p ON oi.product_id = p.id
        INNER JOIN categories c ON p.category_id = c.id
        WHERE o.status NOT IN ('CANCELLED', 'REFUNDED')
        GROUP BY c.id, c.name
        HAVING category_revenue > (
            SELECT AVG(cat_rev) FROM (
                SELECT COALESCE(SUM(oi2.quantity * oi2.unit_price), 0) AS cat_rev
                FROM order_items oi2
                INNER JOIN orders o2 ON oi2.order_id = o2.id
                INNER JOIN products p2 ON oi2.product_id = p2.id
                WHERE o2.status NOT IN ('CANCELLED', 'REFUNDED')
                GROUP BY p2.category_id
            ) AS all_cat_revenues
        )
        ORDER BY category_revenue DESC
    """
    return fetch_all(sql)


