def get_revenue_by_seller():
    """Business problem: Total revenue generated by each seller."""
    sql = """
        SELECT p.seller_id, u.first_name AS seller_first_name, u.last_name AS seller_last_name,
               u.email AS seller_email, COUNT(DISTINCT o.id) AS order_count,
               COALESCE(SUM(oi.quantity * oi.unit_price), 0) AS total_revenue,
               COUNT(DISTINCT p.id) AS products_sold
        FROM order_items oi
        INNER JOIN orders o ON oi.order_id = o.id
        INNER JOIN products p ON oi.product_id = p.id
        INNER JOIN users u ON p.seller_id = u.id
        WHERE o.status NOT IN ('CANCELLED', 'REFUNDED')
        GROUP BY p.seller_id, u.first_name, u.last_name, u.email
        HAVING total_revenue > 0
        ORDER BY total_revenue DESC
    """
    return fetch_all(sql)


def get_monthly_sales_by_category():
    """Monthly sales breakdown by product category."""
    sql = """
        SELECT DATE_FORMAT(o.created_at, '%%Y-%%m') AS month,
               c.id AS category_id, c.name AS category_name,
               COUNT(DISTINCT o.id) AS order_count,
               SUM(oi.quantity) AS units_sold,
               COALESCE(SUM(oi.quantity * oi.unit_price), 0) AS revenue
        FROM order_items oi
        INNER JOIN orders o ON oi.order_id = o.id
        INNER JOIN products p ON oi.product_id = p.id
        INNER JOIN categories c ON p.category_id = c.id
        WHERE o.status NOT IN ('CANCELLED', 'REFUNDED')
        GROUP BY DATE_FORMAT(o.created_at, '%%Y-%%m'), c.id, c.name
        ORDER BY month DESC, revenue DESC
    """
    return fetch_all(sql)


